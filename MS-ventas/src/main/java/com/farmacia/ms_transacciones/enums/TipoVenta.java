package com.farmacia.ms_transacciones.enums;

/**
 * Enum for Sales Modality
 * Defines the unit type in which a product is sold
 */
public enum TipoVenta {
    /**
     * Sale by complete box
     */
    CAJA,

    /**
     * Sale by blister (intermediate packaging)
     */
    BLISTER,

    /**
     * Sale by individual unit
     */
    UNIDAD
}
